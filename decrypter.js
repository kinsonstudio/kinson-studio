function decryptQmc(inputPath) {
  const buffer = fs.readFileSync(inputPath)
  const result = Buffer.alloc(buffer.length)
  for (let i = 0; i < buffer.length; i++) {
    result[i] = buffer[i] ^ QMC_TABLE[i % 256]
  }
  return result
}

// ========== 探测解密后音频的真实格式 ==========
function detectAudioExt(data) {
  if (data.length >= 4) {
    const h = data.slice(0, 4).toString('latin1')
    if (h === 'fLaC') return 'flac'
    if (h === 'OggS') return 'ogg'
  }
  if (data.length >= 3 && data.slice(0, 3).toString('latin1') === 'ID3') return 'mp3'
  if (data.length >= 2 && data[0] === 0xff && (data[1] & 0xe0) === 0xe0) return 'mp3'
  return 'bin'
}

// ========== 统一入口 ==========
function decryptMusic(inputPath) {
  const ext = inputPath.split('.').pop().toLowerCase()
  let data = null

  if (ext === 'ncm') {
    data = decryptNcm(inputPath)
  } else if (ext.startsWith('qmc')) {
    data = decryptQmc(inputPath)
  } else if (['kgm', 'kgma', 'kgg'].includes(ext)) {
    throw new Error('酷狗 KGM 暂不支持')
  } else {
    throw new Error('不支持的加密格式：.' + ext)
  }

  return { data, ext: detectAudioExt(data) }
}

module.exports = { decryptMusic, decryptNcm, decryptQmc, detectAudioExt }
