const crypto = require('crypto')
const fs = require('fs')
const path = require('path')

// ========== RC4 解密（跳过前 1024 字节密钥流） ==========
function rc4Decrypt(data, key, drop = 1024) {
  const S = new Uint8Array(256)
  for (let i = 0; i < 256; i++) S[i] = i
  let j = 0
  for (let i = 0; i < 256; i++) {
    j = (j + S[i] + key[i % key.length]) & 0xff
    const t = S[i]; S[i] = S[j]; S[j] = t
  }
  const out = Buffer.alloc(data.length)
  let i = 0; j = 0
  for (let k = 0; k < data.length + drop; k++) {
    i = (i + 1) & 0xff
    j = (j + S[i]) & 0xff
    const t = S[i]; S[i] = S[j]; S[j] = t
    if (k >= drop) out[k - drop] = data[k - drop] ^ S[(S[i] + S[j]) & 0xff]
  }
  return out
}

// ========== 网易云 NCM 解密 ==========
function decryptNcm(inputPath) {
  const buf = fs.readFileSync(inputPath)
  if (buf.length < 16 || buf.slice(0, 8).toString('latin1') !== 'CTENFDAM') {
    throw new Error('不是有效的 NCM 文件（文件头错误）')
  }

  let off = 10  // 8字节 magic + 2字节 gap

  // coreKey 长度
  let coreKeyLen = buf.readUInt32LE(off)
  if (coreKeyLen <= 0 || coreKeyLen > 4096) coreKeyLen = buf.readUInt32BE(off)
  if (coreKeyLen <= 0 || coreKeyLen > 4096) throw new Error('NCM 密钥段长度异常：' + coreKeyLen)
  off += 4

  // coreKey 数据：XOR 0x64 去混淆
  const coreKey = Buffer.alloc(coreKeyLen)
  for (let i = 0; i < coreKeyLen; i++) coreKey[i] = buf[off + i] ^ 0x64
  off += coreKeyLen

  // metaKey 长度和数据（跳过，不需要元数据）
  let metaKeyLen = buf.readUInt32LE(off)
  if (metaKeyLen <= 0 || metaKeyLen > 16 * 1024 * 1024) metaKeyLen = buf.readUInt32BE(off)
  if (metaKeyLen < 0 || metaKeyLen > 16 * 1024 * 1024) throw new Error('NCM 元数据长度异常：' + metaKeyLen)
  off += 4 + metaKeyLen

  // CRC32 (4字节) + gap (5字节)
  if (off + 9 > buf.length) throw new Error('NCM 文件不完整（CRC/gap）')
  off += 4 + 5

  // 图片长度和数据（跳过封面图）
  if (off + 4 > buf.length) throw new Error('NCM 文件不完整（图片长度）')
  const imgLen = buf.readUInt32LE(off)
  off += 4
  if (imgLen > 0 && imgLen < buf.length) off += imgLen

  if (off >= buf.length) throw new Error('NCM 文件不完整，没有音频数据')

  // AES-128-ECB 解密 coreKey，去掉 17 字节 "neteasecloudmusic" 前缀 → RC4 密钥
  const aesKey = Buffer.from('hzHRAmso5kInbaxW')
  let decryptedCore
  try {
    const d = crypto.createDecipheriv('aes-128-ecb', aesKey, null)
    decryptedCore = Buffer.concat([d.update(coreKey), d.final()])
  } catch (e) {
    throw new Error('NCM 密钥段解密失败：' + e.message.split('\n')[0])
  }
  const rc4Key = decryptedCore.slice(17)
  if (rc4Key.length === 0) throw new Error('NCM 核心密钥解析失败')

  // 剩余全部是加密音频，RC4 解密
  return rc4Decrypt(buf.slice(off), rc4Key, 1024)
}

